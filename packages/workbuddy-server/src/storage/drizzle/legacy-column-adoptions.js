function createColumnAdoptions(tableName, definitions) {
  return Object.freeze(definitions.map(([name, sqlType]) => Object.freeze({
    name,
    addSql: `ALTER TABLE ${tableName} ADD COLUMN ${name} ${sqlType}`,
  })));
}

